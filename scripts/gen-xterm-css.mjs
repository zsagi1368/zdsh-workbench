// Generates src/client/shell/xterm-css.ts from the installed @xterm/xterm
// stylesheet, so the browser bundle can inject it without a CSS build chain.
// Run automatically as part of `pnpm build` (prebuild).
import { readFileSync, writeFileSync, existsSync } from 'node:fs'

const candidates = [
  'node_modules/@xterm/xterm/css/xterm.css',
  'node_modules/@xterm/xterm/lib/xterm.css',
]
const source = candidates.find((path) => existsSync(path))
if (source === undefined) {
  console.error('xterm css not found; run pnpm install first')
  process.exit(1)
}
const css = readFileSync(source, 'utf8')
const out = `/**
 * GENERATED by scripts/gen-xterm-css.mjs — do not edit by hand.
 * Contents of @xterm/xterm's stylesheet, injected with the workbench styles
 * so the terminal renders correctly without any CSS bundling step.
 */
export const XTERM_CSS = ${JSON.stringify(css)}
`
writeFileSync('src/client/shell/xterm-css.ts', out)
console.log(`xterm-css.ts generated (${css.length} bytes)`)
